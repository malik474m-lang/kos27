function getCitySeoText(array $city, string $category = 'microloans'): ?array {
    $db = getDB();
    $stmt = $db->prepare("SELECT * FROM city_seo_texts WHERE city_slug = ? AND category = ? LIMIT 1");
    $stmt->execute([$city['slug'], $category]);
    return $stmt->fetch() ?: null;
}

